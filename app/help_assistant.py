def normalize_help_text(value: str | None) -> str:
    text = unicodedata.normalize("NFD", str(value or ""))
    return "".join(char for char in text if unicodedata.category(char) != "Mn").lower()


def score_help_entry(entry: dict, query: str) -> int:
    normalized_query = normalize_help_text(query)
    if not normalized_query:
        return 0
    words = [
        word
        for word in normalized_query.replace("/", " ").replace("-", " ").split()
        if len(word) > 2 and word not in HELP_STOPWORDS
    ]
    fields = [
        str(entry.get("titulo") or ""),
        str(entry.get("categoria") or ""),
        str(entry.get("pergunta") or ""),
        " ".join(str(word) for word in entry.get("palavrasChave") or []),
    ]
    haystack = normalize_help_text(" ".join(fields))
    score = 0
    if normalized_query in haystack:
        score += 6
    for word in words:
        if word in haystack:
            score += 2
        if word in normalize_help_text(entry.get("titulo")):
            score += 2
        if word in normalize_help_text(" ".join(str(item) for item in entry.get("palavrasChave") or [])):
            score += 2
    return score


def search_help_knowledge_base(entries: list[dict], query: str) -> dict | None:
    ranked = sorted(
        ((score_help_entry(entry, query), entry) for entry in entries),
        key=lambda item: item[0],
        reverse=True,
    )
    best_score, best_entry = ranked[0] if ranked else (0, None)
    return best_entry if best_score >= 2 else None


def summarize_help_metrics(metrics: dict, knowledge_base: list[dict], unanswered: list[dict], tickets: list[dict]) -> dict:
    titles = {entry.get("id"): entry.get("titulo") for entry in knowledge_base}
    question_counts = metrics.get("question_counts") if isinstance(metrics.get("question_counts"), dict) else {}
    useful_counts = metrics.get("useful_counts") if isinstance(metrics.get("useful_counts"), dict) else {}
    not_useful_counts = metrics.get("not_useful_counts") if isinstance(metrics.get("not_useful_counts"), dict) else {}
    top_questions = sorted(question_counts.items(), key=lambda item: int(item[1] or 0), reverse=True)[:5]
    return {
        "top_questions": [
            {"id": item_id, "titulo": titles.get(item_id, item_id), "count": count}
            for item_id, count in top_questions
        ],
        "unanswered_total": len(unanswered),
        "unanswered_open": sum(1 for item in unanswered if item.get("status") in {"nova", "em_analise", "em análise"}),
        "support_clicks": int(metrics.get("support_clicks") or 0),
        "support_tickets_total": len(tickets),
        "support_tickets_open": sum(1 for item in tickets if item.get("status") not in {"resolvido", "resolvida"}),
        "useful_total": sum(int(value or 0) for value in useful_counts.values()),
        "not_useful_total": sum(int(value or 0) for value in not_useful_counts.values()),
    }
